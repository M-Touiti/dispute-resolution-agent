"""Writes the dataset as CSV files, a PostgreSQL seed and a manifest of SHA-256 hashes.

Output is byte-stable: rows sorted by primary key, LF line endings, UTF-8 without BOM, no timestamps.
"""

import csv
import dataclasses
import datetime as dt
import hashlib
import io
import json
import types
import typing
from enum import Enum
from pathlib import Path

from . import GENERATOR_VERSION
from .generator import Config, Dataset
from .model import (
    Authorisation,
    Card,
    Cardholder,
    Dispute,
    DisputeDocument,
    GroundTruth,
    Merchant,
    Transaction,
)


@dataclasses.dataclass(frozen=True, slots=True)
class Table:
    name: str
    row_type: type
    sql_schema: str | None  # None: CSV only (never loaded where the agent can read it)


# Creation order respects foreign keys.
TABLES = (
    Table("cardholders", Cardholder, "ledger"),
    Table("merchants", Merchant, "ledger"),
    Table("cards", Card, "ledger"),
    Table("authorisations", Authorisation, "ledger"),
    Table("transactions", Transaction, "ledger"),
    Table("disputes", Dispute, "intake"),
    Table("dispute_documents", DisputeDocument, "intake"),
    Table("ground_truth", GroundTruth, None),
)

FOREIGN_KEYS = {
    ("cards", "cardholder_id"): "ledger.cardholders",
    ("authorisations", "card_id"): "ledger.cards",
    ("authorisations", "merchant_id"): "ledger.merchants",
    ("transactions", "auth_id"): "ledger.authorisations",
    ("transactions", "card_id"): "ledger.cards",
    ("transactions", "merchant_id"): "ledger.merchants",
    ("transactions", "related_transaction_id"): "ledger.transactions",
    ("disputes", "cardholder_id"): "ledger.cardholders",
    ("disputes", "card_id"): "ledger.cards",
    ("disputes", "transaction_id"): "ledger.transactions",
    ("dispute_documents", "dispute_id"): "intake.disputes",
}

_SQL_BATCH = 500


def columns(row_type: type) -> list[str]:
    return [f.name for f in dataclasses.fields(row_type)]


def rows(dataset: Dataset, table: Table) -> list:
    key = columns(table.row_type)[0]
    return sorted(getattr(dataset, table.name), key=lambda r: getattr(r, key))


def _text(value: object) -> str:
    match value:
        case None:
            return ""
        case bool():
            return "true" if value else "false"
        case dt.datetime():
            return value.astimezone(dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
        case dt.date():
            return value.isoformat()
        case tuple():
            return ";".join(str(v) for v in value)
        case Enum():
            return str(value.value)
        case _:
            return str(value)


def _sql_literal(value: object) -> str:
    match value:
        case None:
            return "NULL"
        case bool():
            return "TRUE" if value else "FALSE"
        case int():
            return str(value)
        case _:
            return "'" + _text(value).replace("'", "''") + "'"


def _sql_type(annotation: object) -> tuple[str, bool]:
    nullable = False
    if isinstance(annotation, types.UnionType):
        args = [a for a in annotation.__args__ if a is not type(None)]
        nullable = len(args) != len(annotation.__args__)
        annotation = args[0]
    if annotation is bool:
        return "BOOLEAN", nullable
    if annotation is int:
        return "BIGINT", nullable
    if annotation is dt.datetime:
        return "TIMESTAMPTZ", nullable
    if annotation is dt.date:
        return "DATE", nullable
    if annotation is str or (isinstance(annotation, type) and issubclass(annotation, Enum)):
        return "TEXT", nullable
    raise TypeError(f"no SQL type for {annotation!r}")


def render_csv(dataset: Dataset, table: Table) -> bytes:
    buf = io.StringIO(newline="")
    writer = csv.writer(buf, lineterminator="\n")
    cols = columns(table.row_type)
    writer.writerow(cols)
    for row in rows(dataset, table):
        writer.writerow([_text(getattr(row, c)) for c in cols])
    return buf.getvalue().encode("utf-8")


def render_sql(dataset: Dataset, config: Config) -> bytes:
    out = [
        "-- Synthetic dispute data. Generated by data/generate.py; do not edit.",
        f"-- seed={config.seed} as_of={config.as_of.isoformat()} generator_version={GENERATOR_VERSION}",
        "-- Ground truth is deliberately absent: it lives in ground_truth.csv for the evaluation only.",
        "BEGIN;",
        "CREATE SCHEMA IF NOT EXISTS ledger;",
        "CREATE SCHEMA IF NOT EXISTS intake;",
    ]
    for table in TABLES:
        if table.sql_schema is None:
            continue
        hints = typing.get_type_hints(table.row_type)
        cols = columns(table.row_type)
        defs = []
        for i, col in enumerate(cols):
            sql_type, nullable = _sql_type(hints[col])
            d = f"    {col} {sql_type}"
            if i == 0:
                d += " PRIMARY KEY"
            elif not nullable:
                d += " NOT NULL"
            ref = FOREIGN_KEYS.get((table.name, col))
            if ref is not None:
                d += f" REFERENCES {ref}"  # the referenced table's primary key
            defs.append(d)
        qualified = f"{table.sql_schema}.{table.name}"
        out.append(f"CREATE TABLE {qualified} (\n" + ",\n".join(defs) + "\n);")
        data = rows(dataset, table)
        for start in range(0, len(data), _SQL_BATCH):
            values = ",\n".join(
                "(" + ", ".join(_sql_literal(getattr(r, c)) for c in cols) + ")"
                for r in data[start : start + _SQL_BATCH]
            )
            out.append(f"INSERT INTO {qualified} ({', '.join(cols)}) VALUES\n{values};")
    out.append("COMMIT;")
    return ("\n".join(out) + "\n").encode("utf-8")


def write_dataset(dataset: Dataset, config: Config, out_dir: Path) -> dict:
    """Writes all files to ``out_dir`` and returns the manifest (also written as manifest.json)."""
    out_dir.mkdir(parents=True, exist_ok=True)
    files: dict[str, bytes] = {f"{t.name}.csv": render_csv(dataset, t) for t in TABLES}
    files["seed.sql"] = render_sql(dataset, config)
    for name, content in files.items():
        (out_dir / name).write_bytes(content)
    manifest = {
        "generator_version": GENERATOR_VERSION,
        "config": {k: _text(v) if isinstance(v, dt.date) else v for k, v in dataclasses.asdict(config).items()},
        "counts": {t.name: len(getattr(dataset, t.name)) for t in TABLES},
        "sha256": {name: hashlib.sha256(content).hexdigest() for name, content in sorted(files.items())},
    }
    (out_dir / "manifest.json").write_bytes((json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode())
    return manifest
